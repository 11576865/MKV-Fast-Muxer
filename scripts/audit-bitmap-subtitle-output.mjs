import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';

const run=(command,args)=>execFileSync(command,args,{maxBuffer:16*1024*1024});
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
function probe(file,selector){
 return JSON.parse(run('ffprobe',['-v','error','-select_streams',selector,
  '-show_streams','-show_packets','-show_data','-show_data_hash','sha256','-of','json',file]));
}
function canonicalPackets(probe){
 if(probe.streams[0]?.codec_name!=='hdmv_pgs_subtitle')return probe.packets;
 // SUP demuxes each PGS segment separately; Matroska stores whole display
 // sets. Compare concatenated segment bytes at each PTS, not packet splits.
 const groups=[];
 for(const packet of probe.packets){
  assert.equal(typeof packet.data,'string','PGS raw packet bytes missing');
  const hex=packet.data.split('\n').filter(line=>line.includes(':'))
   .map(line=>line.slice(line.indexOf(':')+1).trimStart().split('  ')[0].replace(/ /g,''));
  assert.ok(hex.every(part=>/^(?:[0-9a-fA-F]{2})+$/.test(part)),'invalid FFprobe hex dump');
  const data=Buffer.from(hex.join(''),'hex');
  assert.equal(data.length,Number(packet.size),'PGS packet data truncated');
  const last=groups.at(-1);
  if(last&&Number(last.pts_time)===Number(packet.pts_time))last.bytes.push(data);
  else groups.push({pts_time:packet.pts_time,bytes:[data]});
 }
 return groups.map(group=>({pts_time:group.pts_time,data_hash:'SHA256:'+hash(Buffer.concat(group.bytes))}));
}
export function assertCopiedBitmapPackets(source,output,label){
 assert.equal(source.streams.length,1,label+': source stream missing');
 assert.equal(output.streams.length,1,label+': output stream missing');
 assert.equal(output.streams[0].codec_name,source.streams[0].codec_name,label+': codec changed');
 source={...source,packets:canonicalPackets(source)};
 output={...output,packets:canonicalPackets(output)};
 assert.ok(source.packets.length>0,label+': empty source cannot prove copied payload');
 assert.deepEqual(output.packets.map(p=>p.data_hash),source.packets.map(p=>p.data_hash),label+': packet payload differs');
 for(let i=0;i<source.packets.length;i++){
  assert.ok(Number.isFinite(Number(source.packets[i].pts_time))&&Number.isFinite(Number(output.packets[i].pts_time)),label+': missing timestamp');
  assert.ok(Math.abs(Number(source.packets[i].pts_time)-Number(output.packets[i].pts_time))<=0.0011,label+': shifted packet timestamp');
 }
 return {codec:output.streams[0].codec_name,packetCount:source.packets.length,
  packetHashes:output.packets.map(p=>p.data_hash),pts:output.packets.map(p=>p.pts_time)};
}
// Render PNG from already verified raw pixels. Separate helper avoids sending
// output-generated bytes back into the subtitle decoder as a reference oracle.
async function renderFrames(file,subtitleIndex,outDir,label){
 const frames=[];
 for(const seconds of [0.5,1.5,3.5]){
  const pixels=run('ffmpeg',['-hide_banner','-loglevel','error','-y','-copyts','-f','lavfi','-i',
   'color=c=black:s=320x240:r=10:d=4','-i',file,'-filter_complex',
   `[0:v][1:s:${subtitleIndex}]overlay`,'-ss',String(seconds),'-frames:v','1',
   '-pix_fmt','rgb24','-f','rawvideo','pipe:1']);
  assert.equal(pixels.length,320*240*3,label+': no decoded frame');
  const lit=[];
  for(let y=0;y<240;y++)for(let x=0;x<320;x++){
   const i=(y*320+x)*3;
   if(pixels[i]>200&&pixels[i+1]>200&&pixels[i+2]>200)lit.push([x,y]);
  }
  assert.deepEqual(lit,seconds===1.5?Array.from({length:16},(_,i)=>[20+i%4,20+Math.floor(i/4)]):[],label+': bitmap placement/visibility/timing');
  const raw=path.join(outDir,`${label}-${seconds}.rgb`);
  await fs.writeFile(raw,pixels);
  run('ffmpeg',['-hide_banner','-loglevel','error','-y','-f','rawvideo','-pix_fmt','rgb24','-s','320x240','-i',raw,'-frames:v','1',raw.replace(/\.rgb$/,'.png')]);
  frames.push({seconds,frameSha256:hash(pixels),litPixels:lit.length});
 }
 return frames;
}
export async function auditBitmapSubtitleOutput({root,video,output,outDir}){
 await fs.mkdir(outDir,{recursive:true});
 const tracks=[];
 for(const [index,name] of ['bitmap.sup','bitmap.idx'].entries()){
  const source=path.join(root,name),label=index===0?'pgs':'vobsub';
  const packets=assertCopiedBitmapPackets(probe(source,'s:0'),probe(output,`s:${index}`),label);
  const sourceFrames=await renderFrames(source,0,outDir,label+'-source');
  const outputFrames=await renderFrames(output,index,outDir,label+'-output');
  assert.deepEqual(outputFrames,sourceFrames,label+': native decoded frames differ');
  tracks.push({...packets,sourceFrames,outputFrames});
 }
 const media=[];
 for(const selector of ['v:0','a:0']){
  const src=probe(video,selector),dst=probe(output,selector);
  assert.equal(dst.streams.length,src.streams.length,'media stream lost/added');
  if(src.streams.length){
   assert.equal(dst.streams[0].codec_name,src.streams[0].codec_name,'media codec changed');
   assert.deepEqual(dst.packets.map(p=>p.data_hash),src.packets.map(p=>p.data_hash),'media was not copied byte-for-byte');
   media.push({selector,codec:src.streams[0].codec_name,packetCount:src.packets.length});
  }
 }
 const receipt={schema:'softmux-bitmap-native-output-v1',result:'pass',oracle:'native FFprobe packet SHA-256/PTS + FFmpeg decoded bitmap placement/visibility before/during/after; copied media packet SHA-256',outputSha256:hash(await fs.readFile(output)),tracks,media};
 await fs.writeFile(path.join(outDir,'bitmap-native-audit.json'),JSON.stringify(receipt,null,2)+'\n');
 return receipt;
}
